"""Generate firmware/lib/oyster_core/include/oyster_core/lab_profile_gen.h from schemas/lab-profile.json.

The JSON profile is the single source of truth for UUIDs and policies. Run after editing the profile:
    .venv/Scripts/python scripts/gen_lab_profile_header.py
scripts/check.ps1 fails if the committed header is stale.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "schemas" / "lab-profile.json"
OUT = ROOT / "firmware" / "lib" / "oyster_core" / "include" / "oyster_core" / "lab_profile_gen.h"

POLICY = {
    "public": "Policy::Public",
    "link_encryption": "Policy::LinkEncryption",
    "link_authentication": "Policy::LinkAuthentication",
    "app_authorization": "Policy::AppAuthorization",
    "none": "Policy::None",
}


def render(profile: dict) -> str:
    chars = profile["characteristics"]
    rows = []
    for cid, c in chars.items():
        pol = c["policy"]
        rows.append(
            f'    {{"{cid}", "{c["uuid"]}", {POLICY[pol.get("read", "none")]}, '
            f'{POLICY[pol.get("write", "none")]}, {POLICY[pol.get("notify", "none")]}, '
            f'{c.get("max_length", 0)}}},'
        )
    t = profile["transfer"]
    a = profile["app_auth"]
    return "\n".join([
        "// GENERATED by scripts/gen_lab_profile_header.py from schemas/lab-profile.json. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <cstring>",
        "",
        "namespace oyster::lab {",
        "",
        f'constexpr const char* kProfileId = "{profile["profile_id"]}";',
        f"constexpr uint32_t kProfileVersion = {profile['profile_version']};",
        f'constexpr const char* kServiceUuid = "{profile["service_uuid"]}";',
        f'constexpr const char* kObjectId = "{t["object_id"]}";',
        f"constexpr uint32_t kMaxObjectBytes = {t['max_object_bytes']};",
        f"constexpr uint32_t kAuthChallengeBytes = {a['challenge_bytes']};",
        f"constexpr uint32_t kAuthResponseBytes = {a['response_bytes']};",
        f"constexpr uint32_t kAuthTtlS = {a['authorization_ttl_s']};",
        "",
        "enum class Policy : uint8_t { Public, LinkEncryption, LinkAuthentication, AppAuthorization, None };",
        "",
        "struct CharDef {",
        "  const char* id;",
        "  const char* uuid;",
        "  Policy read;",
        "  Policy write;",
        "  Policy notify;",
        "  uint16_t max_length;",
        "};",
        "",
        "constexpr CharDef kChars[] = {",
        *rows,
        "};",
        f"constexpr size_t kCharCount = {len(chars)};",
        "",
        "inline const CharDef* find_char(const char* id) {",
        "  if (id == nullptr) return nullptr;",
        "  for (size_t i = 0; i < kCharCount; ++i) {",
        "    if (std::strcmp(kChars[i].id, id) == 0) return &kChars[i];",
        "  }",
        "  return nullptr;",
        "}",
        "",
        "}  // namespace oyster::lab",
        "",
    ])


def main() -> int:
    text = render(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT} does not match {SRC}; run scripts/gen_lab_profile_header.py")
            return 1
        print("lab_profile_gen.h is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
