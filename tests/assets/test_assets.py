"""Static UI art: flash budget, shapes, loader animation and sanity of firmware/src/assets_gen.cpp."""

import importlib.util
import re
import struct
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
GEN_CPP = ROOT / "firmware" / "src" / "assets_gen.cpp"
HEADER = ROOT / "firmware" / "include" / "assets.h"
SCRIPT = ROOT / "scripts" / "gen_assets.py"
PROVENANCE = ROOT / "assets" / "PROVENANCE.md"
MASCOT = ROOT / "assets" / "mascot" / "oysterOS-logo-512.png"

TRANSPARENT = 0xF81F
FLASH_BUDGET_BYTES = 260_000  # all art together: icons + logo + splash + loader frames
PNG_MAX_BYTES = 900_000
PNG_KEEP = {b"IHDR", b"PLTE", b"tRNS", b"IDAT", b"IEND", b"sRGB", b"gAMA", b"pHYs", b"cHRM"}
ARRAY_RE = re.compile(r"static const uint16_t (\w+)\[(\d+)\] = \{(.*?)\};", re.S)
ANIM_RE = re.compile(r"static const Animation kLoader = \{" + ", ".join([r"(\d+)"] * 6) + r", kLoaderPx\};")
SPLASH_W, SPLASH_H = 240, 135


def _arrays() -> dict[str, list[int]]:
    text = GEN_CPP.read_text(encoding="utf-8")
    out = {}
    for name, count, body in ARRAY_RE.findall(text):
        vals = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]{4}", body)]
        assert len(vals) == int(count), f"{name}: declared {count}, has {len(vals)}"
        out[name] = vals
    return out


def _anim() -> tuple[int, ...]:
    m = ANIM_RE.search(GEN_CPP.read_text(encoding="utf-8"))
    assert m, "kLoader initialiser not found"
    return tuple(int(g) for g in m.groups())


def _icon_ids() -> list[str]:
    enum = re.search(r"enum class IconId : uint8_t \{(.*?)\};", HEADER.read_text(encoding="utf-8"), re.S)
    assert enum, "IconId enum not found in assets.h"
    body = re.sub(r"//[^\n]*", "", enum.group(1))
    names = [n.strip() for n in body.split(",") if n.strip()]
    assert names[-1] == "Count"
    return names[:-1]


def _lum(v: int) -> float:
    r, g, b = ((v >> 11) & 31) * 255 / 31, ((v >> 5) & 63) * 255 / 63, (v & 31) * 255 / 31
    return 0.299 * r + 0.587 * g + 0.114 * b


def _png_chunks(path: Path) -> list[bytes]:
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", path.name
    pos, kinds = 8, []
    while pos < len(data):
        (n,) = struct.unpack(">I", data[pos:pos + 4])
        kinds.append(data[pos + 4:pos + 8])
        pos += 12 + n
    return kinds


def test_generated_header_comment():
    first = GEN_CPP.read_text(encoding="utf-8").splitlines()[0]
    assert first.startswith("// GENERATED by scripts/gen_assets.py")


def test_every_icon_id_has_a_24x24_array():
    arrays = _arrays()
    for name in _icon_ids():
        assert len(arrays.get(f"kIcon{name}", [])) == 24 * 24, name
    assert len(arrays["kLogoPx"]) == 48 * 48
    assert len(arrays["kSplashPx"]) == SPLASH_W * SPLASH_H


def test_loader_animation_shape_and_placement():
    w, h, x, y, frames, fps, *_ = _anim()
    assert (w, h) == (80, 80)
    assert frames == 8 and 1 <= fps <= 8, "gentle: 8 frames, low frame rate"
    assert x + w <= SPLASH_W and y + h <= SPLASH_H
    assert len(_arrays()["kLoaderPx"]) == frames * w * h


def test_flash_budget():
    total = sum(len(v) * 2 for v in _arrays().values())
    assert total == len(_icon_ids()) * 1152 + 48 * 48 * 2 + SPLASH_W * SPLASH_H * 2 + 8 * 80 * 80 * 2
    assert total < FLASH_BUDGET_BYTES


def test_loader_frame_0_equals_splash_region():
    w, h, x, y, *_ = _anim()
    arrays = _arrays()
    splash, loader = arrays["kSplashPx"], arrays["kLoaderPx"]
    region = [splash[(y + r) * SPLASH_W + x + c] for r in range(h) for c in range(w)]
    assert region == loader[:w * h], "frame 0 must match the splash, so the animation starts without a jump"
    assert TRANSPARENT not in loader, "loader frames are opaque (background baked in)"


def test_loader_is_gentle():
    w, h, _, _, frames, *_ = _anim()
    n = w * h
    loader = _arrays()["kLoaderPx"]
    fr = [loader[i * n:(i + 1) * n] for i in range(frames)]
    assert len({tuple(f) for f in fr}) >= 5, "the loop must actually move"
    for i in range(frames):
        a, b = fr[i], fr[(i + 1) % frames]  # includes the wrap from the last frame to frame 0
        mean_step = sum(abs(_lum(p) - _lum(q)) for p, q in zip(a, b, strict=True)) / n
        # a flash needs a large luminance swing over a big part of the screen; stay far below it
        assert mean_step < 8, f"frame {i} -> {(i + 1) % frames}: mean luminance step {mean_step:.1f}/255"


def test_pixel_content_is_sane():
    arrays = _arrays()
    for name in _icon_ids():
        px = arrays[f"kIcon{name}"]
        opaque = [v for v in px if v != TRANSPARENT]
        assert 40 < len(opaque) < len(px) - 40, f"{name}: blank or fully filled icon"
        assert px[0] == TRANSPARENT, f"{name}: corner must be transparent"
        assert len(set(opaque)) >= 2, f"{name}: single colour"
    logo = arrays["kLogoPx"]
    assert logo[0] == TRANSPARENT and logo[len(logo) // 2 + 24] != TRANSPARENT
    assert TRANSPARENT not in arrays["kSplashPx"], "splash is opaque"


def test_mascot_logo_and_icon_use_at_most_16_colours():
    arrays = _arrays()
    for name in ("kLogoPx", "kIconOysterAi"):
        assert 4 <= len(set(arrays[name]) - {TRANSPARENT}) <= 16, name


def test_splash_has_wordmark_and_calm_lower_third():
    splash = _arrays()["kSplashPx"]
    x, y = _anim()[2:4]
    word = [splash[r * SPLASH_W + c] for r in range(20, 85) for c in range(112, 215)]
    assert sum(1 for v in word if _lum(v) > 170) > 150, "light wordmark pixels expected right of the mascot"
    lower = [splash[r * SPLASH_W + c] for r in range(95, SPLASH_H) for c in range(SPLASH_W)]
    assert max(_lum(v) for v in lower) < 60, "lower third stays dark and calm for the status line"
    assert len(set(lower)) <= 24, "lower third: dithered background only, no art"
    assert y + 80 < 95 and x >= 0


def test_accessors_are_bounds_checked_and_const():
    text = GEN_CPP.read_text(encoding="utf-8")
    assert "i < kIconCount ? i : 0" in text
    assert "static_assert(kIconCount == static_cast<unsigned>(IconId::Count)" in text
    for acc in ("const Image& logo()", "const Image& splash()", "const Animation& loader()"):
        assert acc in text
    assert not re.search(r"^(?!static const)\s*uint16_t\s+k\w+\[", text, re.M), "pixel data must stay const"


def test_mascot_source_is_present():
    assert MASCOT.is_file()
    pil = pytest.importorskip("PIL.Image")
    with pil.open(MASCOT) as im:
        assert im.size == (512, 512) and im.mode == "RGBA"


def test_committed_pngs_have_no_ancillary_chunks_and_are_small():
    pngs = sorted((ROOT / "assets").rglob("*.png"))
    assert len(pngs) >= 10
    for p in pngs:
        assert p.stat().st_size < PNG_MAX_BYTES, f"{p.name}: {p.stat().st_size} B"
        extra = set(_png_chunks(p)) - PNG_KEEP
        assert not extra, f"{p.relative_to(ROOT)}: ancillary chunks {sorted(extra)} (text, C2PA, ICC ...)"


def test_no_personal_data_in_assets_text_files():
    for path in (GEN_CPP, SCRIPT, PROVENANCE):
        text = path.read_text(encoding="utf-8")
        # No real email address (the guard against the owner's address leaking in). The generator's own
        # procedural-icon markers ("@skull", "@calc") are not addresses, so match an address shape, not "@".
        assert not re.search(r"[\w.+-]+@[\w-]+\.[\w.-]+", text), path.name
        assert "C:\\Users" not in text and "C:/Users" not in text, path.name


def test_provenance_states_ai_origin_and_terms_caveat():
    text = PROVENANCE.read_text(encoding="utf-8")
    assert "AI-generated" in text
    assert "usage terms" in text


def test_converter_is_deterministic():
    pytest.importorskip("PIL")
    spec = importlib.util.spec_from_file_location("gen_assets", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    first = mod.render_cpp(*mod.build())
    second = mod.render_cpp(*mod.build())
    assert first == second
    assert "0xF81F" in first
