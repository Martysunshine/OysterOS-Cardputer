"""Extracts the two bitmap fonts the firmware draws with from the pinned M5GFX source and writes
simulator/oyster_ui_sim/glyphs.py (printable ASCII only: the firmware replaces everything else with '?').

  AsciiFont8x16  <- src/lgfx/Fonts/Ascii8x16.h   (FontLib8x16, 256 x 16 bytes, row-major, MSB = left pixel)
  Font0 (6x8)    <- src/lgfx/Fonts/glcdfont.h    (font, 256 x 5 column bytes, bit 0 = top pixel)

Usage (needs the PlatformIO library cache of the firmware):
  python simulator/tools/gen_glyphs.py [--m5gfx firmware/.pio/libdeps/cardputer-adv/M5GFX] [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_LIB = REPO / "firmware" / ".pio" / "libdeps" / "cardputer-adv" / "M5GFX"
OUT = REPO / "simulator" / "oyster_ui_sim" / "glyphs.py"
FIRST, LAST = 0x20, 0x7E


def _array_bytes(text: str, array_name: str) -> bytes:
    start = text.index("{", text.index(array_name))
    end = text.index("};", start)
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]{2})", text[start:end]))


def build(lib: Path) -> str:
    fonts = lib / "src" / "lgfx" / "Fonts"
    big = _array_bytes((fonts / "Ascii8x16.h").read_text(encoding="utf-8"), "FontLib8x16[]")
    small = _array_bytes((fonts / "glcdfont.h").read_text(encoding="utf-8"), "font[]")
    if len(big) != 256 * 16 or len(small) != 256 * 5:
        raise SystemExit(f"unexpected font table sizes: {len(big)} / {len(small)}")
    version = json.loads((lib / "library.json").read_text(encoding="utf-8"))["version"]
    rows8 = [big[c * 16 : c * 16 + 16].hex() for c in range(FIRST, LAST + 1)]
    rows6 = [small[c * 5 : c * 5 + 5].hex() for c in range(FIRST, LAST + 1)]
    lines = [
        '"""Glyph bitmaps of the two fonts the OysterOS firmware uses (printable ASCII 0x20..0x7E).',
        "",
        "GENERATED by simulator/tools/gen_glyphs.py - do not edit; rerun the script.",
        f"Glyphs extracted from M5GFX {version} (https://github.com/m5stack/M5GFX), the library",
        "pinned by the firmware. FONT_8X16 is fonts::AsciiFont8x16 (lgfx/Fonts/Ascii8x16.h, M5GFX,",
        "MIT licence, Copyright (c) 2021 M5Stack). FONT_6X8 is fonts::Font0, the classic 5x7 GLCD font in a",
        "6x8 cell (lgfx/Fonts/glcdfont.h, Adafruit GFX Library, BSD licence, Copyright (c) 2012 Adafruit",
        "Industries).",
        "Full licence texts: simulator/README.md.",
        "",
        "FONT_8X16[i]: 16 bytes, one per row, bit 7 = leftmost pixel.",
        "FONT_6X8[i]:  5 bytes, one per column, bit 0 = top pixel (column 5 of the cell is blank).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f"FIRST = 0x{FIRST:02X}",
        f"LAST = 0x{LAST:02X}",
        f'SOURCE = "M5GFX {version}"',
        "",
        "_ROWS_8X16 = (",
    ]
    lines += [f'    "{r}",' for r in rows8]
    lines += [")", "", "_COLS_6X8 = ("]
    lines += [f'    "{r}",' for r in rows6]
    lines += [
        ")",
        "",
        "FONT_8X16 = tuple(bytes.fromhex(r) for r in _ROWS_8X16)",
        "FONT_6X8 = tuple(bytes.fromhex(r) for r in _COLS_6X8)",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--m5gfx", type=Path, default=DEFAULT_LIB)
    ap.add_argument("--check", action="store_true", help="fail when the committed module is out of date")
    args = ap.parse_args()
    text = build(args.m5gfx)
    if args.check:
        same = OUT.read_text(encoding="utf-8") == text
        print("glyphs.py is up to date" if same else "glyphs.py differs from the library source")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
